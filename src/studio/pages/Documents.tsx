/* ---------- Owner monthly report ---------- */

export function OwnerReport() {
  return (
    <Guard area="dashboard">
      <OwnerReportInner />
    </Guard>
  )
}

function OwnerReportInner() {
  const { s, waitlist } = useStudio()
  const t = today()
  const [which, setWhich] = useState<'this' | 'last'>('last')
  const lastRef = format(subMonths(parseISO(t), 1), 'yyyy-MM-dd')
  const ref = which === 'this' ? t : lastRef
  const end = which === 'this' ? t : format(new Date(parseISO(t).getFullYear(), parseISO(t).getMonth(), 0), 'yyyy-MM-dd')
  const m = ownerMetrics(s, end, waitlist, ref)
  const modeRows = (['In-Clinic', 'Virtual', 'In-Home'] as const).map((mode) => [mode, s.appointments.filter((a) => a.status === 'completed' && a.mode === mode && inMonth(a.date, ref)).length])
  const team = therapistTable(s, ref)
  return (
    <>
      <PageHeader eyebrow="Month-end" title="Owner report" actions={<PrintButton />} />
      <Tabs label="Report month" value={which} onChange={setWhich} items={[{ id: 'last', label: format(parseISO(lastRef), 'MMMM yyyy') }, { id: 'this', label: `${format(parseISO(t), 'MMMM')} to date` }]} />
      <Card className="print-card mx-auto max-w-5xl">
        <DocHeader title="Owner report" subtitle={format(parseISO(ref), 'MMMM yyyy')} />
        <div className="grid grid-cols-2 gap-4 lg:grid-cols-4">
          <Stat value={m.sessions} label="Sessions" hint={`${m.siteVisits} site visits`} tone="sage" />
          <Stat value={`${m.noShowRate}%`} label="No-show rate" tone="sage" />
          <Stat value={money(m.invoiced)} label="Invoiced (demo fees)" tone="sage" />
          <Stat value={money(m.collected)} label="Collected" tone="sage" />
        </div>
        <div className="mt-6 grid gap-6 lg:grid-cols-2">
          <div>
            <h2 className="mb-3 font-sans font-bold text-forest">Team</h2>
            <DataTable columns={['Therapist', 'Sessions', 'Home', 'Sites']} rows={team.map((r) => [r.name, r.sessions, r.home, r.siteVisits])} />
          </div>
          <div>
            <h2 className="mb-3 font-sans font-bold text-forest">Visits by mode</h2>
            <DataTable columns={['Mode', 'Completed']} rows={modeRows} />
          </div>
        </div>
        <div className="mt-6">
          <h2 className="mb-3 font-sans font-bold text-forest">Outstanding balances</h2>
          <DataTable
            columns={['Bill to', 'Invoice', 'Issued', 'Balance', 'Status']}
            rows={s.invoices
              .filter((i) => invoiceBalance(i) > 0)
              .map((i) => [i.billTo.kind === 'family' ? `${familyById(s, i.billTo.id)?.name} family` : s.sites.find((x) => x.id === i.billTo.id)?.name ?? '', i.number, shortDate(i.issuedOn), money(invoiceBalance(i)), isOverdue(i, t) ? 'Overdue' : 'Open'])}
          />
        </div>
        <dl className="mt-6 grid gap-x-8 sm:grid-cols-2">
          <Row k="Families on waitlist" v={m.waitlist} />
          <Row k="Invoices paid on time" v={`${m.paidOnTime}%`} />
          <Row k="Total outstanding" v={money(m.outstanding)} />
          <Row k="Site minutes delivered" v={sum(s.siteVisits.filter((v) => v.status === 'completed' && inMonth(v.date, ref)).flatMap((v) => v.attendance.map((a) => a.minutes)))} />
        </dl>
        <p className="mt-6 text-xs text-charcoal-soft">Generated by {platformName} on {fullDate(t)}. Fictional demo data; fees are placeholders.</p>
      </Card>
    </>
  )
}

/* ---------- Progress report (parent & school versions) ---------- */

export function ProgressReportPage() {
  const { id } = useParams()
  const { s, viewer, act } = useStudio()
  const [params, setParams] = useSearchParams()
  const audience = viewer.role === 'parent' ? 'parent' : ((params.get('audience') as 'parent' | 'school') ?? 'parent')
  const [shared, setShared] = useState(false)
  const ch = childById(s, id)
  if (!ch || (viewer.role === 'parent' && ch.familyId !== viewer.familyId)) return <Empty>Report not available.</Empty>
  if (viewer.role === 'frontdesk') return <Guard area="progress">{null}</Guard>
  const sections = progressReport(s, ch.id, audience)
  const goals = s.goals.filter((g) => g.childId === ch.id)
  const dates = [...new Set(s.ratings.filter((r) => goals.some((g) => g.id === r.goalId)).map((r) => r.date))].sort()
  const fam = familyById(s, ch.familyId)
  const consentSchool = s.forms.find((f) => f.familyId === ch.familyId && f.kind === 'consent')?.answers?.shareSchool
  const share = () => {
    act((c) => {
      send(c, 'report', familyById(c.s, ch.familyId), { child: ch.firstName })
      audit(c, `Approved & shared ${audience} progress report`, `${ch.firstName} ${ch.lastName}`)
    })
    setShared(true)
  }
  return (
    <>
      <PageHeader eyebrow="Progress report" title={`${ch.firstName} ${ch.lastName}`} actions={<PrintButton />} />
      {viewer.role !== 'parent' && (
        <Tabs label="Report version" value={audience} onChange={(v) => setParams({ audience: v })} items={[{ id: 'parent', label: 'Parent version' }, { id: 'school', label: 'School version' }]} />
      )}
      {viewer.role !== 'parent' && (
        <div className="no-print mb-4 flex flex-wrap items-center gap-3">
          <AIBadge>AI-written from goal data · therapist approves</AIBadge>
          {audience === 'school' && !consentSchool && <Notice tone="peach">The family has not consented to sharing with school. Print only after consent is on file.</Notice>}
          <Button size="sm" onClick={share} disabled={shared}>
            {shared ? <ShieldCheck aria-hidden /> : <Send aria-hidden />} {shared ? 'Approved & shared' : 'Approve & share with family'}
          </Button>
        </div>
      )}
      <Card className="print-card mx-auto max-w-4xl">
        <DocHeader title={audience === 'parent' ? 'Progress report for families' : 'Progress summary for school'} subtitle={fullDate(today())} />
        <dl className="mb-6 grid gap-x-8 sm:grid-cols-2">
          <Row k="Child" v={`${ch.firstName} ${ch.lastName}`} />
          <Row k="Therapist" v={therapistName(ch.therapistId)} />
          {audience === 'school' && <Row k="Grade" v={ch.grade ?? '—'} />}
          {audience === 'parent' && <Row k="Family" v={fam?.guardians.map((g) => g.name).join(', ') ?? '—'} />}
        </dl>
        {dates.length > 1 && (
          <div className="mb-6">
            <LineChart title="Goal ratings by session (1–5)" labels={dates.map((_, i) => `S${i + 1}`)} series={goals.map((g, i) => ({ name: `${g.domain}: ${g.title.toLowerCase()}`, color: seriesColors[i % 4], values: dates.map((d) => s.ratings.find((r) => r.goalId === g.id && r.date === d)?.score ?? null) }))} />
          </div>
        )}
        <div className="space-y-5">
          {sections.map((sec) => (
            <section key={sec.heading}>
              <h2 className="font-sans text-base font-bold text-forest">{sec.heading}</h2>
              {sec.body.split('\n').map((p, i) => (
                <p key={i} className="mt-1.5 leading-relaxed text-charcoal">
                  {p}
                </p>
              ))}
            </section>
          ))}
        </div>
        <p className="mt-6 text-xs text-charcoal-soft">
          {goals.map((g) => `${g.title}: ${goalTrend(g, s.ratings).first} → ${goalTrend(g, s.ratings).last}`).join(' · ')}. Fictional demo data. Not a clinical document.
        </p>
      </Card>
    </>
  )
}

/* ---------- Family statement ---------- */

export function StatementPage() {
  const { familyId } = useParams()
  const { s, viewer, act } = useStudio()
  const [sent, setSent] = useState(false)
  const fam = familyById(s, familyId)
  if (!fam || (viewer.role === 'parent' && viewer.familyId !== fam.id) || viewer.role === 'therapist') return <Empty>Statement not available.</Empty>
  const invs = s.invoices.filter((i) => i.billTo.kind === 'family' && i.billTo.id === fam.id).sort((a, b) => a.issuedOn.localeCompare(b.issuedOn))
  const balance = sum(invs.map(invoiceBalance))
  const pkg = s.packages.filter((p) => p.familyId === fam.id)
  return (
    <>
      <PageHeader
        eyebrow="Statement"
        title={`${fam.name} family`}
        actions={
          <>
            <PrintButton />
            {viewer.role !== 'parent' && (
              <Button size="sm" disabled={sent} onClick={() => { act((c) => { send(c, 'statement', familyById(c.s, fam.id), { month: today(), amount: balance }); audit(c, 'Sent statement', `${fam.name} family`) }); setSent(true) }}>
                <Send aria-hidden /> {sent ? 'Sent' : 'Email statement'}
              </Button>
            )}
          </>
        }
      />
      <Card className="print-card mx-auto max-w-4xl">
        <DocHeader title="Statement of account" subtitle={`As of ${fullDate(today())}`} />
        <p className="mb-4 text-sm">
          <b>{fam.guardians[0].name}</b>
          <br />
          {fam.address}, {fam.city}, ON {fam.postalCode}
        </p>
        <DataTable
          caption="Invoices and payments"
          columns={['Date', 'Invoice', 'Description', 'Charges', 'Paid', 'Balance']}
          rows={invs.map((i) => [shortDate(i.issuedOn), i.number, i.lines.length === 1 ? i.lines[0].description : `${i.lines.length} visits (${i.batch} batch)`, money(i.total), money(sum(i.payments.map((p) => p.amount))), money(invoiceBalance(i))])}
        />
        {pkg.map((p) => (
          <p key={p.id} className="mt-4 text-sm text-charcoal-soft">
            {p.name}: {p.used} of {p.sessions} sessions used · {p.sessions - p.used} remaining.
          </p>
        ))}
        <div className="mt-6 flex justify-end">
          <div className="rounded-2xl bg-forest px-6 py-4 text-ivory">
            <p className="text-xs uppercase tracking-wider text-ivory/70">Balance due</p>
            <p className="font-serif text-3xl">{money(balance)}</p>
          </div>
        </div>
        <p className="mt-6 text-xs text-charcoal-soft">Demo statement. Fees are placeholders, not real prices.</p>
      </Card>
    </>
  )
}

